// Used by Graders and Floor Assistants to subtract and add stock
async function adjustStockQuantity(itemId, delta, itemName) {
  delta = parseInt(delta) || 0;
  if (delta === 0) return null;

  const items = await sbGet('ab_grade_items');
  const target = items.find(x => x.id == itemId);
  if (!target) return null;

  const currentPcs = parseInt(target.pcs) || 0;
  const newPcs = Math.max(0, currentPcs + delta);

  await sbUpdate('ab_grade_items', itemId, { pcs: newPcs });

  // Toast feedback
  const diffStr = delta > 0 ? `+${delta}` : `${delta}`;
  const actionWord = delta > 0 ? 'Added' : 'Subtracted';
  showToast(`${actionWord} ${Math.abs(delta)} pcs (${target.name}: ${newPcs} total)`);

  return newPcs;
}

