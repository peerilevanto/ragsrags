function requireAuth(allowedRoles) {
  const user = getCurrentUser();
  if (!user) {
    // If not on login page, redirect immediately
    const path = window.location.pathname;
    if (!path.endsWith('login.html') && !path.endsWith('index.html')) {
      window.location.replace('login.html');
      return false;
    }
    return false;
  }

  // Check role restriction if provided
  if (allowedRoles && Array.isArray(allowedRoles) && allowedRoles.length > 0) {
    const role = user.role;
    // admin and super_user can see everything
    if (role === 'admin' || role === 'super_user' || role === 'special') {
      return true;
    }
    if (!allowedRoles.includes(role)) {
      showToast('Access restricted for ' + getRoleName(role), true);
      setTimeout(() => {
        window.location.replace('dashboard.html');
      }, 900);
      return false;
    }
  }

  return true;
}

