// Ã¢â€â‚¬Ã¢â€â‚¬ Universal Database Request Layer Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬Ã¢â€â‚¬
// Automatically connects to Supabase, falls back to synchronized local store
async function sbReq(table, method, body, filter) {
  method = method || 'GET';
  const cfg = getSupabaseConfig();

  // 1. Live Supabase API call
  if (cfg.isConnected) {
    let url = cfg.url.replace(/\/$/, '') + '/rest/v1/' + table;
    const p = [];
    if (method === 'GET') {
      p.push('select=*');
      // Sort created_at desc if applicable
      if (['ab_grade_items', 'customer_items', 'grading_records', 'petty_cash', 'attendance_records', 'inventory_movements', 'suppliers', 'buyers', 'supplier_transactions', 'supplier_payments', 'buyer_transactions', 'buyer_payments', 'orders', 'order_items', 'order_dispatches', 'order_logs', 'warehouse_expenses', 'employee_loans'].includes(table)) {
        p.push('order=created_at.desc');
      }
    }
    if (filter) {
      Object.entries(filter).forEach(([k, v]) => {
        p.push(k + '=eq.' + encodeURIComponent(v));
      });
    }
    if (p.length) url += '?' + p.join('&');

    const headers = {
      'apikey': cfg.key,
      'Authorization': 'Bearer ' + cfg.key,
      'Content-Type': 'application/json'
    };
    if (method === 'POST' || method === 'PATCH') {
      headers['Prefer'] = 'return=representation';
    }

    let writeBody = (method === 'POST' || method === 'PATCH') && body ? Object.assign({}, body) : body;
    try {
      for (let attempt = 0; attempt < 12; attempt++) {
        const res = await fetch(url, {
          method,
          headers,
          body: writeBody ? JSON.stringify(writeBody) : undefined
        });

        if (res.ok) {
          if (method === 'DELETE') return true;
          const txt = await res.text();
          const data = txt ? JSON.parse(txt) : true;
          // Keep local cache mirrored
          if (method === 'GET' && Array.isArray(data)) {
            saveLocalTable(table, data);
          }
          return data;
        }

        const errText = await res.text();
        let errMsg = errText;
        try { const ej = JSON.parse(errText); errMsg = ej.message || ej.hint || ej.details || errText; } catch(e) {}

        // Live tables can lag behind the app schema (e.g. buyers.company).
        // Drop the unknown column and retry so the rest of the row still saves.
        const missingCol = (errMsg.match(/Could not find the '([^']+)' column/) || [])[1];
        if ((method === 'POST' || method === 'PATCH') && missingCol && writeBody && Object.prototype.hasOwnProperty.call(writeBody, missingCol)) {
          console.warn('Supabase schema mismatch on [' + table + ']: dropping column "' + missingCol + '" and retrying');
          delete writeBody[missingCol];
          continue;
        }

        if (method !== 'GET') {
          console.error(`Supabase [${method}] error on [${table}] (HTTP ${res.status}):`, errMsg);
          throw new Error('Supabase: ' + errMsg);
        }
        console.warn(`Supabase GET notice on [${table}]:`, errMsg);
        break;
      }
    } catch(err) {
      // Re-throw write errors so caller can surface them
      if (method !== 'GET') throw err;
      console.warn('Network issue reaching Supabase, utilizing cached store:', err.message);
    }
  }

  // 2. Local Storage Emulation Adapter (only used when Supabase is not connected, or for GET fallbacks)
  const localData = getLocalTable(table);
  if (method === 'GET') {
    if (filter) {
      return localData.filter(item => {
        return Object.entries(filter).every(([k, v]) => item[k] == v);
      });
    }
    return localData;
  }

  if (method === 'POST') {
    const item = Object.assign({}, body, {
      id: body.id || (table + '_' + Date.now().toString(36) + Math.random().toString(36).substr(2, 4)),
      created_at: body.created_at || new Date().toISOString()
    });
    localData.unshift(item);
    saveLocalTable(table, localData);
    return [item];
  }

  if (method === 'PATCH') {
    const id = filter ? filter.id : (body && body.id);
    const idx = localData.findIndex(x => x.id == id);
    if (idx !== -1) {
      localData[idx] = Object.assign({}, localData[idx], body, { updated_at: new Date().toISOString() });
      saveLocalTable(table, localData);
      return [localData[idx]];
    }
    return null;
  }

  if (method === 'DELETE') {
    const id = filter ? filter.id : null;
    const filtered = localData.filter(x => x.id != id);
    saveLocalTable(table, filtered);
    return true;
  }

  return null;
}

